def cash_snapshot():
    data = snapshot()
    for field, tag, values in [
        ("operating_cashflow", "NetCashProvidedByUsedInOperatingActivities", [100, 150]),
        ("capital_expenditure", "PaymentsToAcquirePropertyPlantAndEquipment", [20, 30]),
    ]:
        data["profile"]["fields"][field] = [tag]
        data["companyfacts"]["facts"]["us-gaap"][tag] = {
            "units": {
                "USD": [
                    {
                        "start": f"{year}-01-01",
                        "end": f"{year}-09-30",
                        "filed": f"{year}-10-25",
                        "form": "10-Q",
                        "accn": str(year),
                        "val": value,
                    }
                    for year, value in zip([2023, 2024], values, strict=True)
                ]
            }
        }
    return data


def cash_values(data, cutoff="2024-10-26T05:00:00+00:00"):
    return financials.cashflow_at_cutoff(financials.reported_records(data), cutoff)


def test_cashflow_visibility_and_same_duration_comparison():
    data = cash_snapshot()
    assert cash_values(data, "2024-10-26T04:59:59+00:00")[0] == {}
    values, evidence = cash_values(data)
    assert values == pytest.approx({"operating_cashflow_yoy": 0.5, "free_cashflow_yoy": 0.5})
    assert evidence["current"]["months"] == 9
    assert evidence["prior_year"]["months"] == 9
    # The YTD cash rows cannot replace or extend the quarterly revenue/margin observations.
    assert (
        financials.at_cutoff(financials.reported_records(data), "2024-10-26T05:00:00Z")[1][
            "current"
        ]["end"]
        == "2024-03-31"
    )
    rows = data["companyfacts"]["facts"]["us-gaap"]["NetCashProvidedByUsedInOperatingActivities"][
        "units"
    ]["USD"]
    rows[0]["start"] = "2023-07-01"
    assert cash_values(data)[0] == {}  # Three months cannot compare to nine months.


def test_restatement_cannot_mix_cashflow_and_capex_versions():
    data = cash_snapshot()
    rows = data["companyfacts"]["facts"]["us-gaap"]["NetCashProvidedByUsedInOperatingActivities"][
        "units"
    ]["USD"]
    rows.append(rows[-1] | {"filed": "2024-11-01", "accn": "restatement", "val": 200})
    assert cash_values(data)[0]["free_cashflow_yoy"] == 0.5
    assert cash_values(data, "2024-11-02T05:00:00Z")[0] == {"operating_cashflow_yoy": 1.0}
    rows.append(rows[-1] | {"val": 300})
    assert cash_values(data, "2024-11-02T05:00:00Z")[0] == {}


@pytest.mark.parametrize("prior,expected", [(0, None), (-100, 2.5)])
def test_zero_and_negative_comparison_base(prior, expected):
    data = cash_snapshot()
    data["companyfacts"]["facts"]["us-gaap"]["NetCashProvidedByUsedInOperatingActivities"]["units"][
        "USD"
    ][0]["val"] = prior
    values, _ = cash_values(data)
    assert values.get("operating_cashflow_yoy") == expected


def test_missing_or_stale_cashflow_does_not_disable_income_factors():
    data = snapshot()
    result = financials.prepare_financials(data, ["2024-04-27T20:00:00Z"], [0])
    assert result["columns"]["financial.operating_margin"] == [0.15]
    assert result["columns"]["financial.free_cashflow_yoy"] == [None]
    assert cash_values(cash_snapshot(), "2025-08-01T20:00:00Z")[0] == {}


CASH_TEXT = """Example Company
Consolidated Statements of Cash Flows
(In millions)
Nine Months Ended
September 30, September 30,
2024 2023
Cash generated by operating activities 150 100
Payments for property, plant and equipment (30) (20)
"""
CASH_PROFILE = {
    "statement_title": "Consolidated Statements of Cash Flows",
    "rows": {
        "operating_cashflow": "Cash generated by operating activities",
        "capital_expenditure": "Payments for property, plant and equipment",
    },
}


@pytest.mark.parametrize(
    "header,months",
    [
        ("Three Months Ended", 3),
        ("Six Months Ended", 6),
        ("Nine Months Ended", 9),
        ("Year Ended", 12),
    ],
)
def test_issuer_duration_and_outflow_sign(header, months):
    rows = issuer_financials.statement_rows(
        CASH_TEXT.replace("Nine Months Ended", header), CASH_PROFILE, cashflow=True
    )
    assert {r["period_months"] for r in rows} == {months}
    assert [r["value"] for r in rows] == [150e6, 100e6, 30e6, 20e6]
    with pytest.raises(ValueError, match="cash outflow"):
        issuer_financials.statement_rows(
            CASH_TEXT.replace("(30)", "30"), CASH_PROFILE, cashflow=True
        )
    assert (
        issuer_financials.statement_rows(
            CASH_TEXT.replace("Nine", "Eleven"), CASH_PROFILE, cashflow=True
        )
        is None
    )


def test_cashflow_hypothesis_revised_through_actual_model_and_report(tmp_path, monkeypatch):
    def researcher(context, catalog, **kwargs):
        result = simulated_hypothesis(context, catalog, **kwargs)
        key = (
            "financial.free_cashflow_yoy"
            if kwargs.get("previous")
            else "financial.operating_cashflow_yoy"
        )
        definition = next(d for d in catalog["definitions"] if d["factor_id"] == key)
        assert definition["runnable"]
        result["factor_ids"] = [
            k for k in result["factor_ids"] if not k.startswith("financial.")
        ] + [key]
        result["rationale"] = (
            "SIMULATED cash generation hypothesis; revise after the model feedback."
        )
        return result

    monkeypatch.setattr(study, "simulated_hypothesis", researcher)
    output = tmp_path / "cashflow-study"
    assert (
        main(command(output, "--financials", "--llm", "simulated", "--model", "ridge", "--no-ui"))
        == 0
    )
    result = json.loads((output / "result.json").read_bytes())
    attempts = result["iterations"]["attempts"]
    for attempt, key in zip(
        attempts, ["financial.operating_cashflow_yoy", "financial.free_cashflow_yoy"], strict=True
    ):
        prediction = attempt["prediction"]
        assert key in prediction["factor_ids"]
        assert key in prediction["feature_values"]
    assert result["study"]["financial_comparison"]["status"] == "completed"
    report = (output / "report.html").read_text()
    assert "financial.free_cashflow_yoy" in report
    assert "matching periods" in report


@pytest.mark.parametrize("broken", [None, "income", "cashflow"])
def test_collector_keeps_usable_statement_when_other_section_fails(tmp_path, monkeypatch, broken):
    from datetime import date
    from io import BytesIO
    from types import SimpleNamespace

    host = "https://issuer.example"
    resources = {
        host: b'<a href="/release">Earnings</a>',
        host + "/release": (
            b'<meta name="published_time" content="2024-10-25">'
            b'<a href="/statement.pdf">Statements</a>'
        ),
        host + "/statement.pdf": b"%PDF-original offline fixture",
    }
    monkeypatch.setattr(
        issuer_financials,
        "build_opener",
        lambda *a: SimpleNamespace(
            open=lambda request, **kwargs: BytesIO(resources[request.full_url])
        ),
    )
    monkeypatch.setattr(issuer_financials, "statement_date", lambda *a: date(2024, 10, 25))

    def parse(raw, profile, *, cashflow=False):
        section = "cashflow" if cashflow else "income"
        if section == broken:
            raise ValueError("Unsupported fixture " + section)
        if cashflow:
            return issuer_financials.statement_rows(CASH_TEXT, CASH_PROFILE, cashflow=True), 3
        return [{"field": "revenue", "value": 100, "end": "2024-09-30", "tag": "Revenues"}], 1

    monkeypatch.setattr(issuer_financials, "parse_statement", parse)
    profile = {
        "issuer": {
            "index_url": host,
            "allowed_hosts": ["issuer.example"],
            "archive": "html_links",
            "release_pattern": "/release$",
            "pdf_pattern": r"\.pdf$",
            "cashflow": CASH_PROFILE,
        }
    }
    result = issuer_financials.collect_issuer("KO", tmp_path, profile)
    assert {r["page"] for r in result["records"]} == (
        {1, 3} if broken is None else {3} if broken == "income" else {1}
    )
    assert all(r["available_at"] == "2024-10-26T05:00:00+00:00" for r in result["records"])
    cash = [r for r in result["records"] if r["field"] == "operating_cashflow"]
    if broken != "cashflow":
        assert all(
            r["period_months"] == 9 and r["period_kind"] == "reported_cashflow_duration"
            for r in cash
        )
    assert [f["section"] for f in result["failures"]] == ([] if broken is None else [broken])


def test_explicit_row_aliases_preserve_label_and_reject_conflict():
    profile = CASH_PROFILE | {
        "rows": CASH_PROFILE["rows"]
        | {
            "operating_cashflow": [
                "Net Cash Provided by Operating Activities",
                "Cash generated by operating activities",
            ]
        }
    }
    rows = issuer_financials.statement_rows(CASH_TEXT, profile, cashflow=True)
    assert rows[0]["tag"] == "Cash generated by operating activities"
    with pytest.raises(ValueError, match="conflicting"):
        issuer_financials.statement_rows(
            CASH_TEXT + "Net Cash Provided by Operating Activities 999 100\n",
            profile,
            cashflow=True,
        )
